# Writes paper/claims_check.md: every sentence of paper/sections/*.tex that uses a macro from generated/numbers.tex,
# with its macros, their values and their source files. Also fails if a section uses a backslash command that is
# neither a number macro nor a known LaTeX / document command (catches misspelled or missing macros).
#
# Usage (from the project root): .venv\Scripts\python.exe paper\make_claims_check.py
import json
import re
import sys
from datetime import date
from pathlib import Path

P = Path(__file__).resolve().parent
IDX = json.loads((P / "generated" / "numbers_index.json").read_text(encoding="utf-8"))
KNOWN = {"section", "subsection", "paragraph", "label", "ref", "citeTODO", "reviewcheck", "texttt", "TODO", "item",
         "begin", "end", "emph", "epsilon", "lambda", "kappa", "in", "infty", "textit", "textbf", "ensuremath", "cite",
         "centering", "footnotesize", "caption", "toprule", "midrule", "bottomrule", "multicolumn",
         # Float placement in the sections (Stage 8j).
         "input", "includegraphics", "textwidth", "columnwidth", "url",
         # PDF bookmark text for a section title with math (Stage 9, Task 22).
         "texorpdfstring"}
# abstract_short is the abstract in main.tex (Stage 8l); abstract_long is kept but not included.
ORDER = ["abstract_short", "intro", "related", "setup", "methods", "results", "discussion", "limitations", "conclusion",
         "reproducibility", "appendix", "ai_declaration", "abstract_long"]


def clean(v):
    return re.sub(r"\\ensuremath\{([^{}]*)\}", r"\1", v).replace("~", " ").replace("{,}", ",")


def main():
    rows, unknown = [], []
    for name in ORDER:
        f = P / "sections" / f"{name}.tex"
        text = "\n".join(re.sub(r"(?<!\\)%.*$", "", l) for l in f.read_text(encoding="utf-8").splitlines())
        for cmd in set(re.findall(r"\\([A-Za-z]+)", text)):
            if cmd not in IDX and cmd not in KNOWN:
                unknown.append((name, cmd))
        flat = re.sub(r"\s+", " ", text)
        for sent in re.split(r"(?<=[.;])\s+(?=[A-Z\\])", flat):
            ms = [m for m in re.findall(r"\\([A-Za-z]+)", sent) if m in IDX]
            if ms:
                rows.append((name, sent.strip(), list(dict.fromkeys(ms))))
    lines = ["# Claims check", "",
             f"Generated by `paper/make_claims_check.py` on {date.today().isoformat()} from `paper/sections/*.tex` and "
             "`paper/generated/numbers_index.json`. Each row is a sentence that uses at least one number macro; the "
             "macro values and sources are those written by `paper/make_numbers_tex.py`.", "",
             "| Section | Sentence (LaTeX) | Macro = value | Source |", "|---|---|---|---|"]
    for sec, s, ms in rows:
        s_md = s.replace("|", "\\|")
        if len(s_md) > 300:
            s_md = s_md[:297] + "..."
        vals = "<br>".join(f"`\\{m}` = {clean(IDX[m]['value'])}" for m in ms)
        srcs = "<br>".join(dict.fromkeys(f"`{IDX[m]['source']}`" for m in ms))
        lines.append(f"| {sec} | {s_md} | {vals} | {srcs} |")
    (P / "claims_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote paper/claims_check.md ({len(rows)} sentences)")
    if unknown:
        print("UNKNOWN commands (not a number macro, not in the known list):")
        for s, c in sorted(unknown):
            print(f"  {s}: \\{c}")
        sys.exit(1)


if __name__ == "__main__":
    main()
