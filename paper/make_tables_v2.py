def num(v, d=3):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "n/a"
    t = f"{v:.{d}f}"
    return t[1:] if t.startswith("-") and float(t) == 0 else t


def m(v, d=3):
    return f"${num(v, d)}$"


def mr(v, lo, hi, d=3):
    # Mean with the seed range (min to max over seeds).
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "n/a"
    if lo is None or (isinstance(lo, float) and np.isnan(lo)):
        return f"${num(v, d)}$"
    return f"${num(v, d)}$ {{\\scriptsize (${num(lo, d)}$ to ${num(hi, d)}$)}}"


def bnd(v, d=3):
    # Interval bound: keeps the sign of a slightly negative bound that rounds to zero (-0.000), so that the interval
    # does not look as if it excluded zero (Stage 9m).
    return "n/a" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.{d}f}"


def mci(v, lo, hi, d=3):
    return f"${num(v, d)}$ {{\\scriptsize [${bnd(lo, d)}$, ${bnd(hi, d)}$]}}"


def stack(*lines):
    # Two or more lines in one cell (a one-column tabular in braces); used to narrow wide tables, same content.
    return r"{\begin{tabular}[t]{@{}c@{}}" + r"\\".join(lines) + r"\end{tabular}}"


def stackl(*lines):
    # Left-aligned stacked lines (long headings on two lines; same text).
    return r"{\begin{tabular}[t]{@{}l@{}}" + r"\\".join(lines) + r"\end{tabular}}"


def mrs(v, lo, hi, d=3):
    # mr() with the seed range on a second line.
    if v is None or (isinstance(v, float) and np.isnan(v)) or lo is None or (isinstance(lo, float) and np.isnan(lo)):
        return mr(v, lo, hi, d)
    return stack(f"${num(v, d)}$", f"{{\\scriptsize (${num(lo, d)}$ to ${num(hi, d)}$)}}")


def mcis(v, lo, hi, d=3):
    # mci() with the confidence interval on a second line.
    return stack(f"${num(v, d)}$", f"{{\\scriptsize [${bnd(lo, d)}$, ${bnd(hi, d)}$]}}")


def esc(s):
    return str(s).replace("_", r"\_").replace("%", r"\%")


def intc(v):
    return f"{int(v):,}".replace(",", "{,}")


def tabular(colspec, header, rows, resize):
    # resize=True scales to \textwidth; resize="shrink" scales only if the tabular is wider than \textwidth (box 0 is
    # measured with \ifdim, no extra package), so narrow tables are never enlarged.
    if resize == "shrink":
        lines = tabular(colspec, header, rows, False)
        return [r"\sbox0{%"] + lines[:-1] + [lines[-1] + "}%",
                r"\ifdim\wd0>\textwidth\resizebox{\textwidth}{!}{\usebox0}\else\usebox0\fi"]
    lines = [r"\resizebox{\textwidth}{!}{%"] if resize else []
    lines += [f"\\begin{{tabular}}{{{colspec}}}", r"\toprule"]
    for h in (header if isinstance(header[0], list) else [header]):
        lines.append(" & ".join(h) + r" \\")
    lines.append(r"\midrule")
    for r in rows:
        if r == "MIDRULE":
            lines.append(r"\midrule")
        elif isinstance(r, str):
            lines.append(r)
        else:
            lines.append(" & ".join(r) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}" + ("}" if resize else "")]
    return lines


def write(name, caption, label, colspec, header, rows, sources, notes=(), wide=False, size="footnotesize",
          tabcolsep=None, resize=False, panels=None):
    # One float per file, always \begin{table}[t] (the document is one-column; wide is kept for the call sites only).
    # size / tabcolsep / resize (\resizebox to \textwidth, kept at scale 0.8 or above) and panels (a list of
    # (panel title, colspec, header, rows), one tabular each) control the layout; the content is unchanged.
    env = "table"
    lines = [f"% Generated by paper/make_tables_v2.py on {date.today().isoformat()}. Do not edit.",
             *[f"% Source: {s}" for s in sources],
             f"\\begin{{{env}}}[t]", r"\centering", f"\\{size}"]
    if tabcolsep is not None:
        lines.append(f"\\setlength{{\\tabcolsep}}{{{tabcolsep}pt}}")
    lines += [f"\\caption{{{caption}}}", f"\\label{{{label}}}"]
    if panels:
        for i, (title, cs, hd, rw) in enumerate(panels):
            if i:
                lines.append(r"\par\medskip")
            lines.append(r"\textit{" + title + r"}\par\smallskip")
            lines += tabular(cs, hd, rw, resize)
    else:
        lines += tabular(colspec, header, rows, resize)
    if notes:
        lines.append(r"\par\smallskip\parbox{\linewidth}{\scriptsize " + " ".join(notes) + "}")
    lines += [f"\\end{{{env}}}", ""]
    (OUT / f"{name}.tex").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote generated/{name}.tex")


def note(claim, value, source):
    NUMBERS.append((claim, value, source))


