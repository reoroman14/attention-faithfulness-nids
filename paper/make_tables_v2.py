def t6():
    rows = []
    S = {yr: D.success_long(yr) for yr in ("2017", "2018")}
    E = {yr: D.excess_long(yr) for yr in ("2017", "2018")}

    def cell(yr, mode, atk, e, col):
        d = S[yr][0]
        g = D.agg_seeds(d[(d["mode"] == mode) & (d.attack == atk) & (d.eps == e)], ["attack"], col)
        return (g["mean"].iloc[0], g.lo.iloc[0], g.hi.iloc[0]) if len(g) else (np.nan, np.nan, np.nan)

    # V1 (primary row set) from the Stage 8a3 per-seed values, the source of the V1 macros. 2018 has no flagged source
    # row, so its V1 equals V0 (checked here for every cell) and one 2018 column is shown.
    s5 = D.sens("stage5")

    def sv(yr, v, q, **f):
        x = s5[(s5.dataset == yr) & (s5.variant == v) & (s5.quantity == q)]
        for k, val in f.items():
            x = x[x[k] == val]
        return x.sort_values("seed").value.to_numpy()

    def v1(q, d=3, **f):
        a8, b8 = sv(2018, "V1", q, **f), sv(2018, "V0", q, **f)
        assert len(a8) and np.array_equal(a8, b8), (q, f)
        x = sv(2017, "V1", q, **f)
        return mr(x.mean(), x.min(), x.max(), d)

    rows.append(r"\multicolumn{4}{l}{\textit{Top-10 rollout mass ratio adversarial / clean (1 = unchanged)}} \\")
    for atk in ("A2", "A3_lam100", "A3_lam1000", "A3norm_w0.5"):
        for e in (0.25, 0.5, 1.0):
            v = [cell(yr, "constrained", atk, e, "mass_ratio_rollout") for yr in ("2017", "2018")]
            rows.append([f"{D.ATTACK_NAMES[atk]}, $\\epsilon = {num(e, 2)}$", mr(*v[0]),
                         v1("mass_ratio_rollout", mode="constrained", attack=atk, eps=e), mr(*v[1])])
            if atk == "A2" and e == 1.0:
                note("A2 top-10 rollout mass ratio at eps 1.0 (2017 / 2018), 7 common classes",
                     f"{v[0][0]:.3f} / {v[1][0]:.3f}", "; ".join(S["2017"][1] + S["2018"][1]))
    v = [cell(yr, "unconstrained", "A2", 0.5, "mass_ratio_rollout") for yr in ("2017", "2018")]
    rows.append([stackl("A2 unconstrained reference,", r"standardised $\epsilon = 0.5$"), mr(*v[0]),
                 v1("mass_ratio_rollout", mode="unconstrained", attack="A2", eps=0.5), mr(*v[1])])
    note("Unconstrained A2 mass ratio at standardised eps 0.5 (2017 / 2018)", f"{v[0][0]:.3f} / {v[1][0]:.3f}",
         "; ".join(S["2017"][1] + S["2018"][1]))
    rows.append("MIDRULE")
    rows.append(r"\multicolumn{4}{l}{\textit{Evasion success, A1 minus A0}} \\")
    for e in (0.25, 0.5, 1.0):
        cells = []
        for yr in ("2017", "2018"):
            d = S[yr][0]
            x = d[(d["mode"] == "constrained") & (d.eps == e)].pivot_table(index="seed", columns="attack", values="success")
            diff = x["A1"] - x["A0"]
            cells.append(mr(diff.mean(), diff.min(), diff.max()))
            if e == 1.0:
                note(f"A1 minus A0 success at eps 1.0, {yr}", f"{diff.mean():.3f} ({diff.min():.3f} to {diff.max():.3f})",
                     "; ".join(S[yr][1]))
        rows.append([f"$\\epsilon = {num(e, 2)}$", cells[0], v1("A1_minus_A0_success", eps=e), cells[1]])
    rows.append("MIDRULE")
    rows.append(r"\multicolumn{4}{l}{" + stackl(r"\textit{Flipped A1 rows, $\epsilon = 1$: margin AOPC gap change vs clean,}",
                                                r"\textit{minus the A0 change}") + r"} \\")
    labs = {"ig_zero": "IG", "occlusion": "Occlusion", "static_ig": "Static IG (class mean)", "attn_rollout": "Attn. rollout",
            "attn_mean": "Attn. layer mean", "attn_last": "Attn. last layer", "static_rollout": "Static rollout (class mean)", "abs_x": r"$|x|$",
            "random": "Random"}
    for meth, lab in labs.items():
        cells = []
        for yr in ("2017", "2018"):
            d = E[yr][0]
