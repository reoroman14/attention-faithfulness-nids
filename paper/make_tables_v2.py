def split_range(s):
    try:
        lo, hi = str(s).split(" to ")
        return float(lo), float(hi)
    except ValueError:
        return np.nan, np.nan


def t3():
    a, f = D.clean_cmp()
    names = {"attn_last": "Attn. last layer", "attn_mean": "Attn. layer mean", "attn_rollout": "Attn. rollout",
             "ig_zero": "IG", "gshap": "GradientSHAP", "occlusion": "Occlusion", "treeshap_xgb": "TreeSHAP (XGB)",
             "abs_x": r"$|x|$", "random": "Random"}
    # Two floats (Stage 8h, page height): agreement (heading moved into the caption, rank columns dropped because they
    # are empty for these rows) and faithfulness.
    # V1 (primary row set): the same quantities on the explanation rows without a near duplicate in train, from the
    # Stage 8b per-seed values (the source of the V1 macros); V0 stays the Stage 7c comparison file.
    cv = pd.read_csv(D.RES / "stage8" / "clean_variants.csv")
    cv = cv[cv.variant == "V1"]
    cvo = pd.read_csv(D.RES / "stage8" / "clean_variants_ordering.csv").set_index(["variant", "metric"])

    def v1(yr, metric, meth, ref=None):
        x = cv[(cv.dataset == int(yr)) & (cv.metric == metric) & (cv.method == meth)]
        x = x[x.ref == ref] if ref else x[x.ref.isna()]
        return mrs(x.value.mean(), x.value.min(), x.value.max())

    rows = []
    for at in ("attn_rollout", "attn_mean", "attn_last"):
        for ref in ("ig_zero", "gshap", "occlusion", "treeshap_xgb"):
            x = a[(a.method_a == at) & (a.method_b == ref) & (a.metric == "spearman")].iloc[0]
            l7, h7 = split_range(x.seed_range_2017)
            l8, h8 = split_range(x.seed_range_2018)
            rows.append([f"{names[at]} vs {names[ref]}", mrs(x.mean_2017, l7, h7), v1("2017", "spearman", at, ref),
                         mrs(x.mean_2018, l8, h8), v1("2018", "spearman", at, ref)])
            if at == "attn_rollout" and ref == "ig_zero":
                note("Spearman rollout vs IG, 7 common classes (2017 / 2018)",
                     f"{x.mean_2017:.3f} / {x.mean_2018:.3f}", "results/stage7/stage7c/stage7c_cmp2017_agreement.csv")
    agree_rows, rows = rows, []
    meths = ["attn_rollout", "attn_mean", "attn_last", "ig_zero", "gshap", "occlusion", "abs_x", "random"]
    for metric, lab, asc in (("del_auc", (r"Deletion AUC (train-mean masking,", r"lower is more faithful; rank 1 = lowest)"),
                              True),
                             ("ins_auc", (r"Insertion AUC (train-mean masking,", r"higher is more faithful; rank 1 = highest)"),
                              False)):
        if rows:
            rows.append("MIDRULE")
        rows.append(r"\multicolumn{7}{l}{" + stackl(*[r"\textit{" + s + "}" for s in lab]) + r"} \\")
        x = f[(f.metric == metric) & (f.mask_baseline == "train_mean")].set_index("method").loc[meths]
        rk7 = x.mean_2017.rank(ascending=asc, method="min").astype(int)
        rk8 = x.mean_2018.rank(ascending=asc, method="min").astype(int)
        o1 = cvo.loc[("V1", metric)]
        for meth in meths:
            r = x.loc[meth]
            l7, h7 = split_range(r.seed_range_2017)
            l8, h8 = split_range(r.seed_range_2018)
            rows.append([names[meth], mrs(r.mean_2017, l7, h7), v1("2017", metric, meth), mrs(r.mean_2018, l8, h8),
                         v1("2018", metric, meth), f"{m(rk7[meth], 0)} / {m(o1[f'rank2017_{meth}'], 0)}",
                         f"{m(rk8[meth], 0)} / {m(o1[f'rank2018_{meth}'], 0)}"])
            if metric == "del_auc" and meth in ("attn_rollout", "abs_x", "ig_zero", "random"):
                note(f"Deletion AUC {meth}, train-mean masking, 7 common classes (2017 / 2018)",
                     f"{r.mean_2017:.3f} / {r.mean_2018:.3f}", "results/stage7/stage7c/stage7c_cmp2017_faithfulness.csv")
        rho = spearmanr(x.mean_2017, x.mean_2018).statistic
        rows.append(stackl(r"\textit{Spearman of the method}", r"\textit{ordering, 2017 vs 2018}") + r" & \multicolumn{6}{c}{"
                    + f"V0: {m(rho)}; V1: {m(o1.spearman_orderings)}" + r"} \\")
        note(f"Spearman rank correlation of the 8-method ordering by {metric}, 2017 vs 2018 (7 common classes)",
             f"{rho:.3f}; ranks 2017 {dict(rk7)}; ranks 2018 {dict(rk8)}",
             "results/stage7/stage7c/stage7c_cmp2017_faithfulness.csv")
    common = ["Macro over the 7 common attack classes, mean over 3 seeds (seed range in brackets).",
              "V0: all rows of the clean explanation set, including test rows with a near duplicate in the training set "
              "(Table~\\ref{t_limitations_data}); V1 (primary): those rows removed."]
    yr_head = ["", r"\multicolumn{2}{c}{2017}", r"\multicolumn{2}{c}{2018}"]
    write("t_clean_agreement", "Clean-data agreement, 2017 vs 2018 (7 common classes): Spearman between attention and "
          "attribution rankings, all explanation rows (V0) and without near duplicates (V1).", "t_clean_agreement", "lcccc",
          [yr_head, ["Quantity", "V0", "V1", "V0", "V1"]], agree_rows,
          ["results/stage7/stage7c/stage7c_cmp2017_agreement.csv", "results/stage8/clean_variants.csv"], common,
          resize="shrink")
    write("t_clean_faith", "Clean-data faithfulness, 2017 vs 2018 (7 common classes), all explanation rows (V0) and "
          "without near duplicates (V1).", "t_clean_faith", "lcccccc",
          [yr_head + ["", ""], ["Quantity", "V0", "V1", "V0", "V1", stack("Rank 2017", "V0 / V1"),
                                stack("Rank 2018", "V0 / V1")]], rows,
          ["results/stage7/stage7c/stage7c_cmp2017_faithfulness.csv", "results/stage8/clean_variants.csv",
           "results/stage8/clean_variants_ordering.csv"],
          common[:1] + ["Ranks: position of each method among the 8 methods, computed from the 7-class means, separately "
                        "per metric, dataset and row set. The last row of each block is the Spearman correlation of the "
                        "2017 and 2018 rankings."] + common[1:], resize="shrink")


