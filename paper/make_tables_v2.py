# ---------------------------------------------------------------- T14 (appendix): parameter randomisation

def t14():
    import json
    from scipy.stats import hypergeom
    R = D.randomisation()
    k, F = 10, len(json.loads((D.RES / "stage1" / "features.json").read_text(encoding="utf-8")))
    names = {"attn_rollout": "Attn. rollout", "attn_mean": "Attn. layer mean", "attn_last": "Attn. last layer",
             "ig_zero": "IG (absolute)", "ig_zero_signed": "IG (signed)"}
    levels = [("cascade_top1", "Last block (block 3) re-initialised",
               ["attn_rollout", "attn_mean", "attn_last", "ig_zero", "ig_zero_signed"]),
              ("cascade_top3_tokenizer", "All blocks and the feature tokenizer re-initialised",
               ["attn_rollout", "ig_zero", "ig_zero_signed"]),
              ("indep_block1", "First block (block 1) alone re-initialised", ["attn_rollout", "ig_zero"])]
    rows = []
    for lv, title, methods in levels:
        rows.append(r"\multicolumn{5}{l}{\textit{" + title + r"}} \\")
        for m in methods:
            cells = [names[m]]
            for yr in ("2017", "2018"):
                for met in ("spearman_vs_original", f"jaccard@{k}_vs_original"):
                    x = R[(R.dataset == yr) & (R.level == lv) & (R.method == m) & (R.metric == met)].iloc[0]
                    assert x.n_seeds == 3
                    cells.append(mr(x["mean"], x.lo, x.hi))
                    if met.startswith("spearman") and m in ("attn_rollout", "ig_zero", "ig_zero_signed", "attn_last"):
                        note(f"Parameter randomisation {lv}, {m}, Spearman vs original, {yr} (7 common classes), mean "
                             "(seed range)", f"{x['mean']:.3f} ({x.lo:.3f} to {x.hi:.3f})", x.source)
            rows.append(cells)
    i = np.arange(k + 1)
    chance = float((hypergeom(F, k, k).pmf(i) * i / (2 * k - i)).sum())
    n_rand = int(R.n_min.min())
    assert n_rand == int(R.n_max.max())
    write("t_randomisation", "Parameter randomisation check: similarity between the explanation of the original model "
          "and of the partly re-initialised model (7 common classes).", "t_randomisation", "lcccc",
          [["", r"\multicolumn{2}{c}{2017}", r"\multicolumn{2}{c}{2018}"],
           ["Explainer", "Spearman", f"Jaccard@{k}", "Spearman", f"Jaccard@{k}"]], rows,
          sorted(set(R.source)),
          [f"Per row, on the first {n_rand} rows per class of the clean explanation set (all rows of this subset), "
           "between the explanation of the trained model and that of a copy with the named parts re-initialised; the "
           "classifier head is kept. Spearman of the feature importances; Jaccard of the top-" + str(k) + " features. "
           "IG: training-mean baseline, original class; absolute IG is ranked by magnitude, signed IG by its signed "
           f"value. Macro over the 7 common classes, mean over 3 seeds (seed range). Chance level of the top-{k} "
           f"Jaccard for {F} features: {chance:.3f}. Unchanged explanation: 1."], resize="shrink")


