# Writes paper_srep/generated/numbers.tex and numbers_index.json: every macro of paper_v3/gen/make_numbers_v3.py (run
# unchanged, imported as a module, output redirected), plus the result macros added for the Scientific Reports version.
# Also writes paper_srep/generated/srep_numbers.tex: the numbering of the display items and of the Supplementary items
# (from srep_common.py), shared by main.tex and supplementary.tex so that the two documents cannot disagree.
# Read-only on results/, paper/ and paper_v3/.
#
# Usage (from the project root): .venv\Scripts\python.exe paper_srep\gen\make_numbers_srep.py
import pandas as pd

import srep_common as S
import make_numbers_v3 as M                       # paper_v3/gen/make_numbers_v3.py, output redirected by srep_common


def srep_extra():
    # Rows of the A6x comparison whose outcome changed: flipped status plus undetected status, an upper bound on the
    # number of distinct rows. Written as words for the abstract ("changed the outcome of no row").
    f = M.A6X / "rowlevel_A6x_vs_A6.csv"
    r = pd.read_csv(f)
    n = int(r.flip_diff.abs().sum() + r.undet_diff.abs().sum())
    phrase = "no row" if n == 0 else ("one row" if n == 1 else f"at most {n:,} rows".replace(",", "{,}"))
    M.add("sxOutcomeChangedPhrase", phrase, M.rel(f) + " (sum of |flip_diff| and |undet_diff| in words)")


def numbering():
    lines = ["% Generated by paper_srep/gen/make_numbers_srep.py from paper_srep/gen/srep_common.py. Do not edit.",
             "% Numbering of the display items (main.tex) and of the Supplementary items (supplementary.tex)."]
    for i, (_, mac) in enumerate(S.MAIN_FIGURES, 1):
        lines.append(f"\\newcommand{{\\{mac}}}{{{i}}}")
    for i, (_, mac) in enumerate(S.MAIN_TABLES, 1):
        lines.append(f"\\newcommand{{\\{mac}}}{{{i}}}")
    for i, (_, mac, _) in enumerate(S.SUPP_NOTES, 1):
        lines.append(f"\\newcommand{{\\{mac}}}{{{i}}}")
    for i, (_, mac) in enumerate(S.SUPP_TABLES, 1):
        lines.append(f"\\newcommand{{\\{mac}}}{{S{i}}}")
    for i, (_, mac) in enumerate(S.SUPP_FIGURES, 1):
        lines.append(f"\\newcommand{{\\{mac}}}{{S{i}}}")
    (S.GEN / "srep_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote generated/srep_numbers.tex ({len(lines) - 2} numbering macros)")


if __name__ == "__main__":
    M.NEW = M.NEW + (srep_extra,)
    M.main()
    numbering()
